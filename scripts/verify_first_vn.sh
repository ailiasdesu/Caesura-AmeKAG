#!/usr/bin/env bash
# =============================================================================
#  Caesura (AmeKAG) — verify_first_vn.sh
#
#  First-VN E2E acceptance (task book §6): walks the COMPLETE USER CREATION
#  FLOW a new author takes, end to end. Where verify_golden_vn.sh regresses
#  the Runtime feature surface, this gate verifies the product journey:
#
#    1. template discovery   manifest lists blank/basic/live2d/kag3/showcase
#    2. project creation     copy the basic template -> projects/first_vn_e2e
#                            (simulates PM create), caesura.project.json born
#    3. project metadata     name / template / language fields readable
#    4. project open         entry.lua present + created story passes ks_check
#    5. script validation    ks_check on tests/projects/first_vn/story.ks,
#                            zero violations AND zero warnings
#    6. asset discovery      every storage="..." referenced by first_vn
#                            resolves on disk (project-local first, shared
#                            pool fallback)
#    7. headless run         stock sample_game_headless.lua drives the whole
#                            story to RESULT DONE
#    8. choice A             FIRST_VN_CHOICE=1 -> DONE + ROUTE sun
#    9. choice B             FIRST_VN_CHOICE=2 -> DONE + ROUTE rain
#   10. save                 [save slot=7] reports success headless
#   11. load                 [load slot=8] command flow exercised (graceful
#                            empty-slot miss); real round-trip restore is
#                            owned by golden_vn + C++ SaveManager suites
#   12. package              package_game.sh -> dist/first_vn bundle built
#   13. packaged launch      index.html + cache/story/story.lua +
#                            MANIFEST.txt shipped (real browser launch is the
#                            separate §9 Web verification task — manual)
#
#  Usage (from repo root):  bash scripts/verify_first_vn.sh
#  Exit: 0 = all checks passed, 1 = any check failed.
# =============================================================================
set -uo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$HERE/.." && pwd)"
cd "$ROOT" || { echo "[verify-firstvn] cannot cd repo root"; exit 1; }

LUA="external/lua/lua.exe"
if [ ! -f "$LUA" ]; then LUA="$(command -v lua || true)"; fi
if [ -z "$LUA" ] || ! [ -e "$LUA" ]; then
    echo "[verify-firstvn] FATAL: no Lua interpreter (expected external/lua/lua.exe)"; exit 1
fi

STORY="${FIRSTVN_STORY:-tests/projects/first_vn/story.ks}"
PROJECT_DIR="${FIRSTVN_DIR:-tests/projects/first_vn}"
DRIVER_STOCK="tests/scripts/sample_game_headless.lua"
DRIVER_FIRSTVN="tests/scripts/first_vn_headless.lua"
TEMPLATE_DIR="tools/project_templates"
FRAME_BUDGET="${FIRSTVN_FRAMES:-200000}"
PKG_OUT="dist/first_vn"

PASS=0; FAIL=0
note() { echo "[verify-firstvn] $*"; }

check() { # check <name> <exitcode> [detail]
    if [ "$2" -eq 0 ]; then PASS=$((PASS + 1)); note "PASS  $1"
    else FAIL=$((FAIL + 1)); note "FAIL  $1  (rc=$2 ${3:-})"; fi
}

echo ""
echo "================================================================"
echo "  First-VN E2E verification — user creation flow ($STORY)"
echo "================================================================"

# ---- 1. Template discovery -------------------------------------------------
note "Step 1: template discovery ($TEMPLATE_DIR/manifest.json)"
T_RC=0
MANIFEST="$TEMPLATE_DIR/manifest.json"
if [ ! -f "$MANIFEST" ]; then
    note "  manifest missing: $MANIFEST"
    T_RC=1
else
    for t in blank basic live2d kag3 showcase; do
        if ! grep -q "\"id\": *\"$t\"" "$MANIFEST"; then
            note "  template id missing from manifest: $t"; T_RC=1
        elif [ ! -d "$TEMPLATE_DIR/$t" ]; then
            note "  template dir missing: $TEMPLATE_DIR/$t"; T_RC=1
        fi
    done
fi
[ "$T_RC" -eq 0 ] && note "  found: blank / basic / live2d / kag3 / showcase"
check "template discovery: manifest lists 5 templates with dirs" "$T_RC"

# ---- 2. Project creation (simulate PM create from the basic template) ------
note "Step 2: project creation (copy basic -> tmp projects/first_vn_e2e)"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
NEW_PROJ="$WORK/projects/first_vn_e2e"
C_RC=0
mkdir -p "$WORK/projects"
cp -r "$TEMPLATE_DIR/basic" "$NEW_PROJ" || C_RC=1
if [ "$C_RC" -eq 0 ] && [ ! -f "$NEW_PROJ/caesura.project.json" ]; then
    note "  caesura.project.json not generated by create-copy"; C_RC=1
fi
[ "$C_RC" -eq 0 ] && note "  created $NEW_PROJ (caesura.project.json present)"
check "project creation: basic template copies into projects/first_vn_e2e" "$C_RC"

# ---- 3. Project metadata ----------------------------------------------------
note "Step 3: project metadata (name / template / language)"
M_RC=0
PJ="$NEW_PROJ/caesura.project.json"
grep -q '\"name\": *"basic"'       "$PJ" || { note "  field name=basic missing";       M_RC=1; }
grep -q '\"template\": *"basic"'   "$PJ" || { note "  field template=basic missing";   M_RC=1; }
grep -q '\"language\": *"zh\"'    "$PJ" || { note "  field language=zh missing";      M_RC=1; }
[ "$M_RC" -eq 0 ] && note "  name=basic, template=basic, language=zh"
check "project metadata: name/template/language fields valid" "$M_RC"

# ---- 4. Project open ---------------------------------------------------------
note "Step 4: project open (entry.lua + created-story contract check)"
O_RC=0
[ -f "$NEW_PROJ/entry.lua" ] || { note "  entry.lua missing in created project"; O_RC=1; }
if [ "$O_RC" -eq 0 ]; then
    "$LUA" scripts/ks_check.lua "$NEW_PROJ/story.ks" >/dev/null 2>&1 || O_RC=1
fi
[ "$O_RC" -eq 0 ] && note "  entry.lua present, created story.ks passes contracts"
check "project open: entry.lua + created story ks_check clean" "$O_RC"

# ---- 5. Script validation (zero violations AND zero warnings) ---------------
note "Step 5: script validation ($STORY)"
KSC_OUT="$($LUA scripts/ks_check.lua "$STORY" 2>&1)"
KSC_RC=$?
echo "$KSC_OUT" | sed 's/^/  /'
WARN_COUNT="$(printf "%s" "$KSC_OUT" | grep -c "^\[WARN\]" || true)"
V_RC=$KSC_RC
[ "$WARN_COUNT" -gt 0 ] && V_RC=1
check "script validation: ks_check zero violations, zero warnings" "$V_RC" "($WARN_COUNT warnings)"

# ---- 6. Asset discovery (resolve every storage= reference) -------------------
note "Step 6: asset discovery (storage refs resolve: project-first, pool-fallback)"
cat > "$WORK/assets_check.lua" <<LUA_EOF
-- first_vn asset-discovery helper (generated by scripts/verify_first_vn.sh)
-- usage: lua assets_check.lua <story.ks> <project_dir>
-- Resolves every storage=/sprite="..." reference project-first, then
-- against the repo shared pool ("." fallback).
local story = arg[1]
local roots = { arg[2], "." }
local f = assert(io.open(story, "r"))
local seen, order = {}, {}
for line in f:lines() do
    for attr, ref in line:gmatch('(%a+)%s*=%s*"([^"]+)"') do
        if (attr == "storage" or attr == "sprite") and not seen[ref] then
            seen[ref] = true
            order[#order + 1] = ref
        end
    end
end
f:close()
if #order == 0 then
    print("no storage/sprite references found in " .. story)
    os.exit(1)
end
local missing = 0
for _, ref in ipairs(order) do
    local ok = false
    for _, root in ipairs(roots) do
        local fh = io.open(root .. "/" .. ref, "r")
        if fh then fh:close(); ok = true; break end
    end
    if ok then
        print("  ok       " .. ref)
    else
        missing = missing + 1
        print("  MISSING  " .. ref)
    end
end
print("refs=" .. #order .. " missing=" .. missing)
os.exit(missing > 0 and 1 or 0)
LUA_EOF
A_OUT="$($LUA "$WORK/assets_check.lua" "$STORY" "$PROJECT_DIR" 2>&1)"
A_RC=$?
echo "$A_OUT" | sed 's/^/  /'
check "asset discovery: every referenced asset exists" "$A_RC"

# ---- 7. Headless full run (stock driver) -------------------------------------
note "Step 7: headless run (stock driver, frame budget=$FRAME_BUDGET)"
MAIN_OUT="$(SAMPLE_STORY="$STORY" SAMPLE_FRAMES="$FRAME_BUDGET" $LUA "$DRIVER_STOCK" 2>&1)"
MAIN_RC=$?
printf "%s\n" "$MAIN_OUT" | grep -E "RESULT|ENDING|FATAL" | sed 's/^/  /' || true
if [ "$MAIN_RC" -eq 0 ] && printf "%s\n" "$MAIN_OUT" | grep -q "RESULT DONE"; then
    check "headless run: first_vn runs to DONE" 0
else
    check "headless run: first_vn runs to DONE" "$MAIN_RC"
fi

# ---- 8./9. Choice A / Choice B (branch actually taken via f.route) -----------
note "Step 8: choice A (FIRST_VN_CHOICE=1 -> branch sun)"
CA_OUT="$(SAMPLE_STORY="$STORY" SAMPLE_FRAMES="$FRAME_BUDGET" FIRST_VN_CHOICE=1 $LUA "$DRIVER_FIRSTVN" 2>&1)"
CA_RC=$?
printf "%s\n" "$CA_OUT" | grep -E "RESULT|ROUTE|ENDING|FATAL" | sed 's/^/  /' || true
if [ "$CA_RC" -eq 0 ] && printf "%s\n" "$CA_OUT" | grep -q "RESULT DONE" \
   && printf "%s\n" "$CA_OUT" | grep -q "^ROUTE sun"; then
    check "choice A: option 1 -> branch sun reaches [end]" 0
else
    check "choice A: option 1 -> branch sun reaches [end]" "$CA_RC" "(expected ROUTE sun + DONE)"
fi

note "Step 9: choice B (FIRST_VN_CHOICE=2 -> branch rain)"
CB_OUT="$(SAMPLE_STORY="$STORY" SAMPLE_FRAMES="$FRAME_BUDGET" FIRST_VN_CHOICE=2 $LUA "$DRIVER_FIRSTVN" 2>&1)"
CB_RC=$?
printf "%s\n" "$CB_OUT" | grep -E "RESULT|ROUTE|ENDING|FATAL" | sed 's/^/  /' || true
if [ "$CB_RC" -eq 0 ] && printf "%s\n" "$CB_OUT" | grep -q "RESULT DONE" \
   && printf "%s\n" "$CB_OUT" | grep -q "^ROUTE rain"; then
    check "choice B: option 2 -> branch rain reaches [end]" 0
else
    check "choice B: option 2 -> branch rain reaches [end]" "$CB_RC" "(expected ROUTE rain + DONE)"
fi

# ---- 10./11. Save / Load (one run feeds both checks) --------------------------
note "Step 10/11: save + load flow (headless markers)"
SL_OUT="$(SAMPLE_STORY="$STORY" SAMPLE_FRAMES="$FRAME_BUDGET" FIRST_VN_CHOICE=1 $LUA "$DRIVER_FIRSTVN" 2>&1)"
SL_RC=$?
SAVE_OK=0; LOAD_ATTEMPT=0
printf "%s\n" "$SL_OUT" | grep -q "\[SaveCmd\] Saved to slot 7"            && SAVE_OK=1
printf "%s\n" "$SL_OUT" | grep -q "\[SaveCmd\].*slot 8"                    && LOAD_ATTEMPT=1
if [ "$SL_RC" -eq 0 ] && [ "$SAVE_OK" -eq 1 ]; then
    check "save: [save slot=7] completes headless (Saved marker)" 0
else
    check "save: [save slot=7] completes headless (Saved marker)" 1 "(see output above)"
fi
note "  load annotation: headless has no C++ SaveManager -- [load slot=8] is an"
note "  EMPTY-slot probe verifying the load command flow continues gracefully;"
note "  real round-trip restore is owned by golden_vn + C++ SaveManager suites."
if [ "$SL_RC" -eq 0 ] && [ "$LOAD_ATTEMPT" -eq 1 ]; then
    check "load: [load slot=8] flow exercised, story continues (graceful miss)" 0
else
    check "load: [load slot=8] flow exercised, story continues (graceful miss)" 1 "(expected slot-8 load attempt + DONE)"
fi

# ---- 12. Package ----------------------------------------------------------------
note "Step 12: package (package_game.sh -> $PKG_OUT)"
# Windows note: freshly written dirs can be locked briefly (indexer / sync
# clients). Pre-clean with retries, then allow one full packaging retry.
PKG_RC=1
for attempt in 1 2; do
    for i in 1 2 3 4 5; do
        rm -rf "$PKG_OUT" 2>/dev/null || { sleep 2; continue; }
        break
    done
    if bash scripts/package_game.sh --out "$PKG_OUT" "$STORY" >"$WORK/pkg.log" 2>&1; then
        PKG_RC=0
        break
    fi
    sleep 3
done
if [ "$PKG_RC" -ne 0 ]; then
    note "  packaging failed; last log tail:"
    tail -20 "$WORK/pkg.log" | sed 's/^/  /'
fi
check "package: dist/first_vn bundle builds" "$PKG_RC"

# ---- 13. Packaged launch artifacts -----------------------------------------------
note "Step 13: packaged launch artifacts ($PKG_OUT)"
P_RC=0
for artifact in index.html cache/story/story.lua MANIFEST.txt demo/first_vn/story.ks; do
    if [ -f "$PKG_OUT/$artifact" ]; then
        note "  ok       $PKG_OUT/$artifact"
    else
        note "  MISSING  $PKG_OUT/$artifact"; P_RC=1
    fi
done
check "packaged launch: bundle artifacts present (browser launch = manual §9)" "$P_RC"
note "  manual step (§9 Web verification task): serve $PKG_OUT and pick the"
note "  scene from the dropdown in a real browser."

echo ""
echo "================================================================"
TOTAL=$((PASS + FAIL))
if [ "$FAIL" -eq 0 ]; then
    echo "  RESULT: PASS ($PASS/$TOTAL checks)"
    echo "================================================================"
    exit 0
else
    echo "  RESULT: FAIL ($FAIL/$TOTAL checks failed)"
    echo "================================================================"
    exit 1
fi
